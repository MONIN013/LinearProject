function values = prepare_tunable_trajectory_parameters( ...
        reference, feedforward, capacity)
%PREPARE_TUNABLE_TRAJECTORY_PARAMETERS Pack signals into fixed target arrays.
validateattributes(reference, {'numeric'}, ...
    {'vector', 'nonempty', 'real', 'finite'}, mfilename, 'reference');
validateattributes(feedforward, {'numeric'}, ...
    {'vector', 'nonempty', 'real', 'finite'}, mfilename, 'feedforward');
validateattributes(capacity, {'numeric'}, ...
    {'scalar', 'integer', 'positive', 'finite'}, mfilename, 'capacity');

reference = double(reference(:));
feedforward = double(feedforward(:));
sampleCount = numel(reference);
if numel(feedforward) ~= sampleCount
    error("NikonMotor:TrajectoryLengthMismatch", ...
        "Reference and feedforward must contain the same number of samples.");
end
if sampleCount > capacity
    error("NikonMotor:TrajectoryBufferExceeded", ...
        ['The trajectory has %d samples, but the built target buffer holds ' ...
         '%d. Shorten the trajectory or increase the buffer and rebuild once.'], ...
        sampleCount, capacity);
end

% Repeat the last sample so the fixed-buffer implementation retains the old
% direct-lookup saturation behavior while the delayed enable path winds down.
values = struct( ...
    "p_ref", repmat(reference(end), capacity, 1), ...
    "p_ff", repmat(feedforward(end), capacity, 1), ...
    "p_count", double(sampleCount));
values.p_ref(1:sampleCount) = reference;
values.p_ff(1:sampleCount) = feedforward;
end
